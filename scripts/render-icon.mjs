// Renders the brand artwork with Electron's own Chromium. Run: npm run icon
// - build/icon.svg -> build/icon.png (1024x1024). electron-builder converts it
//   to .icns (macOS) and .ico (Windows) and uses it as the Linux icon.
// - build/tray-icon-16.svg + build/tray-icon.svg -> src/main/tray/icon.ts, the
//   16px (@1x) and 32px (@2x) menu-bar PNGs embedded as base64 so no extra
//   resource file has to be packaged.
import { app, BrowserWindow } from 'electron'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const size = 1024

app.disableHardwareAcceleration()
// Each capture closes its window; keep the app alive between captures.
app.on('window-all-closed', () => undefined)
void app.whenReady().then(async () => {
  // Each SVG is drawn at 1024x1024 on a transparent page, captured, then scaled.
  const captured = {}
  for (const file of ['build/icon.svg', 'build/tray-icon-16.svg', 'build/tray-icon.svg']) {
    const svg = readFileSync(join(root, file), 'utf8')
    const html = `<!doctype html><html><body style="margin:0;background:transparent">${svg}</body></html>`
    const win = new BrowserWindow({
      show: false,
      width: size,
      height: size,
      transparent: true,
      frame: false,
      useContentSize: true,
      webPreferences: { offscreen: true }
    })
    await win.loadURL(`data:text/html;base64,${Buffer.from(html).toString('base64')}`)
    captured[file] = await win.webContents.capturePage()
    win.destroy()
  }
  const icon = captured['build/icon.svg'].resize({ width: size, height: size })
  writeFileSync(join(root, 'build/icon.png'), icon.toPNG())
  const tray1x = captured['build/tray-icon-16.svg']
    .resize({ width: 16, height: 16, quality: 'best' })
    .toPNG()
    .toString('base64')
  const tray2x = captured['build/tray-icon.svg']
    .resize({ width: 32, height: 32, quality: 'best' })
    .toPNG()
    .toString('base64')

  const module = `/**
 * CiteFox menu-bar mark: the app icon's fox head as a one-colour silhouette on
 * a transparent ground, 16px (@1x) and 32px (@2x). macOS uses it as a template
 * image so the menu bar tints it for light and dark mode.
 *
 * Generated by \`npm run icon\` from build/tray-icon-16.svg and build/tray-icon.svg.
 * Do not edit by hand.
 */
export const TRAY_ICON_PNG: Uint8Array = Buffer.from(
  '${tray1x}',
  'base64'
)

export const TRAY_ICON_PNG_2X: Uint8Array = Buffer.from(
  '${tray2x}',
  'base64'
)
`
  writeFileSync(join(root, 'src/main/tray/icon.ts'), module)
  app.quit()
})
